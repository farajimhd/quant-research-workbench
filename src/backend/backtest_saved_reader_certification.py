def certify_saved_reader_source(approved_backend_fingerprint: str) -> str:
    from . import historical_runtime_versions as versions
    if (type(approved_backend_fingerprint) is not str
            or re.fullmatch(r"[0-9a-f]{64}", approved_backend_fingerprint) is None
            or approved_backend_fingerprint != versions.LOADED_BACKEND_FINGERPRINT
            or approved_backend_fingerprint != versions.backend_source_fingerprint()):
        raise ValueError("Saved reader source differs from its approved loaded identity")
    if (type(SAVED_READER_SOURCE_AST) is not dict
            or tuple(SAVED_READER_SOURCE_AST) != REQUIRED_READER_SOURCE_FILES
            or not REQUIRED_READER_SOURCE_FILES
            or any(type(k) is not str or type(v) is not str
                   or re.fullmatch(r"[0-9a-f]{64}", v) is None
                   for k, v in SAVED_READER_SOURCE_AST.items())):
        raise ValueError("Saved reader source closure differs from its closed declaration")
    own_path = Path(__file__).resolve()
    own_source = own_path.read_text(encoding="utf-8")
    own_ast = ast.parse(own_source)
    expected_imports = ast.parse("from __future__ import annotations\nimport ast\nfrom hashlib import sha256\nimport json\nfrom pathlib import Path\nimport re\n").body
    expected_docstring = "Independent current-source certificate for saved read-only reconstruction.\n\nHistorical writer execution certificates are not current-reader certificates.\nThe explicit import closure conservatively includes deferred consumer imports.\nThe approved registry fingerprint additionally seals this module and its pins.\n"
    nodes = own_ast.body
    if (len(nodes) != 10 or ast.get_docstring(own_ast, clean=False) != expected_docstring
            or any(ast.dump(actual, include_attributes=False) != ast.dump(expected, include_attributes=False)
                   for actual, expected in zip(nodes[1:7], expected_imports))
            or any(type(node) is not ast.Assign or len(node.targets) != 1
                   or type(node.targets[0]) is not ast.Name or node.targets[0].id != name
                   for node, name in zip(nodes[7:9], ("SAVED_READER_SOURCE_AST", "REQUIRED_READER_SOURCE_FILES")))
            or type(nodes[9]) is not ast.FunctionDef or nodes[9].name != "certify_saved_reader_source"):
        raise ValueError("Saved reader certifier module envelope changed")
    if (ast.literal_eval(nodes[7].value) != SAVED_READER_SOURCE_AST
            or ast.literal_eval(nodes[8].value) != REQUIRED_READER_SOURCE_FILES):
        raise ValueError("Saved reader loaded declaration differs from disk source")
    compiled = compile(own_source, __file__, "exec", dont_inherit=True)
    functions = tuple(value for value in compiled.co_consts
                      if type(value) is type(certify_saved_reader_source.__code__)
                      and value.co_name == "certify_saved_reader_source")
    if len(functions) != 1 or functions[0] != certify_saved_reader_source.__code__:
        raise ValueError("Saved reader loaded certifier differs from disk source")
    root = Path(__file__).resolve().parents[2]
    actual = {}
    for relative, expected in SAVED_READER_SOURCE_AST.items():
        path = root / relative
        if (not path.is_file() or path.is_symlink()
                or path.resolve().is_relative_to(root) is False):
            raise ValueError("Saved reader source leaf is unavailable")
        summary = ast.dump(ast.parse(path.read_text(encoding="utf-8")), include_attributes=False)
        observed = sha256(summary.encode("utf-8")).hexdigest()
        if observed != expected:
            raise ValueError("Saved reader pinned source changed: " + relative)
        actual[relative] = observed
    # Own raw metadata/function bytes are bound by the separately approved
    # complete backend fingerprint, not an editable self-issued digest.
    return sha256(json.dumps({"scope": "saved_read_only_no_execution_or_resume",
                              "reader_backend_fingerprint": approved_backend_fingerprint,
                              "source_ast": actual}, sort_keys=True,
                             separators=(",", ":")).encode("utf-8")).hexdigest()
