    def test_recursive_windows_against_sequential_reference(self):
        # Long enough to expose initialization, accumulated error and decay.
        source=f"""SELECT toDate('2026-09-18') AS session_date,toUInt32(1000) AS resolution_ms,
            toUInt32(14700+number) AS bucket_index,
            toUInt64(100000 + (number%17)*31 - (number%7)*13) AS close_int,
            close_int+100 AS high_int,close_int-70 AS low_int FROM numbers(1000)"""
        self.c.query(S.technical_from_source(self.db,self.build,self.day,'EMA',self.attempt,source),'fixture_technical',False)
        rows=self.c.query(f"SELECT * FROM {S.table(self.db,'technical')} WHERE ticker='EMA' ORDER BY bucket_index",'fixture_values')
        states={p:None for p in S.EMAS}
        signal=None
        prev=None
        gain_sum=loss_sum=tr_sum=ag=al=atr=0.
        for i,row in enumerate(rows):
            close=(100000+(i%17)*31-(i%7)*13)/10000.
            high,low=close+.01,close-.007
            for p in S.EMAS:
                a=2/(p+1)
                states[p]=close if states[p] is None else a*close+(1-a)*states[p]
                self.assertAlmostEqual(row[f'ema_{p}'],states[p],places=10)
            line=states[12]-states[26]
            signal=line if signal is None else .2*line+.8*signal
            self.assertAlmostEqual(row['macd_signal'],signal,places=10)
            self.assertAlmostEqual(row['macd_histogram'],line-signal,places=10)
            tr=high-low if prev is None else max(high-low,abs(high-prev),abs(low-prev))
            if i<14:
                tr_sum+=tr
                if i==13: atr=tr_sum/14
            else: atr=(atr*13+tr)/14
            self.assertAlmostEqual(row['atr_14'],atr,places=10)
            if prev is not None:
                gain,loss=max(0,close-prev),max(0,prev-close)
                if i<=14:
                    gain_sum+=gain;loss_sum+=loss
                    if i==14: ag,al=gain_sum/14,loss_sum/14
                else: ag,al=(ag*13+gain)/14,(al*13+loss)/14
            expected=0. if i<14 else 100. if al<=0 else 100.-100./(1+ag/al)
            self.assertAlmostEqual(row['rsi_14'],expected,places=8)
            self.assertEqual(row['rsi_ready'],int(i>=14))
            self.assertEqual(row['atr_ready'],int(i>=13))
            prev=close
        self.assertEqual(len(rows),1000)

